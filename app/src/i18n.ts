export const dictionaries: Record<Lang, Dict> = { tr, en, es };
export type Key = keyof Dict;

export function makeT(lang: Lang) {
  const d = dictionaries[lang] ?? en;
  return (key: Key, vars?: Record<string, string | number>) =>
    (d[key] ?? en[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => String(vars?.[k] ?? ''));
}

export type T = ReturnType<typeof makeT>;

export const LOCALES: Record<Lang, string> = { tr: 'tr-TR', en: 'en-US', es: 'es-ES' };

export function detectLang(): Lang {
  const n = (typeof navigator !== 'undefined' ? navigator.language : 'en').slice(0, 2);
  return n === 'tr' || n === 'es' ? n : 'en';
}
